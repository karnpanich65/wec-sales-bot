    def _resolve_state(self, user_id: str, platform: str,
                       referral: dict,
                       skey: str = "",
                       page_id: str = "") -> tuple[dict, bool]:
        skey = skey or user_id
        if skey in _lead_states:
            return _lead_states[skey], False

        # RAM ไม่มี — เซิร์ฟเวอร์เพิ่ง restart หรือเป็นลูกค้าใหม่จริง
        # 17 ส.ค. 2026 — บั๊กจริง: ของเดิมส่ง page_id จาก referral._page_id เท่านั้น
        # ข้อความปกติ (ไม่ได้มาจากแอด) ไม่มีคีย์นั้น -> ส่ง "" ไปหา session
        # แต่ตอนบันทึกใช้ page_id จริง -> คีย์ไม่ตรง -> หาไม่เจอ -> นึกว่าลูกค้าใหม่
        # ผลคือ "ทุกครั้งที่ deploy บอททักทายใหม่ + ถามข้อ 1 ซ้ำ" ทั้งที่คุยไปครึ่งทางแล้ว
        _pid = page_id or (referral or {}).get("_page_id", "") or ""
        loaded = self._load_session(user_id, _pid)
        if loaded:
            loaded.setdefault("data", {})
            loaded.setdefault("awaiting", None)
            loaded["psid"] = user_id
            _lead_states[skey] = loaded
            _conversations.setdefault(skey, [])
            print(f"[SESSION] restored {user_id[:8]}... "
                  f"fields={list(loaded.get('data', {}).keys())}")
            return loaded, False

        state = self._blank_state(platform, referral)
        state["psid"] = user_id
        # ลูกค้าใหม่ = มาจากเพจ/แอดด้วยเหตุผลบางอย่างเสมอ -> เข้าโหมดถามเลย
        # (ไม่ทิ้งคำถามลูกค้า และไม่ปล่อยให้จบแค่ "สวัสดีครับ")
        # ตั้งใจให้เป็น True เสมอ -> QUALIFY_TRIGGERS จึงไม่ได้คุมว่า "เริ่มถามเมื่อไหร่"
        # มันคุมแค่ว่า "ข้อความนี้ต้องส่งให้ AI ตอบไหม"
        # ใครจะแก้ QUALIFY_TRIGGERS ให้รู้ไว้ว่ามันไม่มีผลกับจังหวะเริ่มถาม
        state["qualifying"] = True
        _lead_states[skey] = state
        _conversations[skey] = []
        return state, True

    def _load_session(self, user_id: str, page_id: str = "") -> dict | None:
        """ดึง state เก่าจากชีต — ใช้เฉพาะตอน RAM ไม่มี (เซิร์ฟเวอร์เพิ่ง restart)

        Phase 5.8: เดิม timeout 2.5 วิ ยิงครั้งเดียว Apps Script cold start
        มักเกิน 2.5 วิ -> โหลดไม่ทัน -> ระบบนึกว่าลูกค้าใหม่ -> ถามซ้ำตั้งแต่ข้อ 1
        แก้: ยิงซ้ำได้ 1 ครั้งด้วย timeout ที่ยาวขึ้น (รวมแย่สุด ~8 วิ ยังตอบทัน)
        """
        if not (FEATURE_PERSIST and APPS_SCRIPT_URL):
            return None
        for attempt, tmo in enumerate(SESSION_LOAD_TIMEOUTS, start=1):
            try:
                r = requests.post(
                    APPS_SCRIPT_URL,
                    json={"action": "get_session", "psid": user_id,
                          "page_id": page_id},
                    timeout=tmo,
                )
                if r.status_code != 200:
                    return None
                j = r.json()
                st = j.get("state")
                return st if isinstance(st, dict) and st else None
            except Exception as e:
                last = attempt == len(SESSION_LOAD_TIMEOUTS)
                print(f"[SESSION LOAD {'ERROR' if last else 'RETRY'}] "
                      f"attempt {attempt}/{len(SESSION_LOAD_TIMEOUTS)} "
                      f"(timeout={tmo}s): {e}")
        return None

