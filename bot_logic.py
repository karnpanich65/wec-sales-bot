    # เก็บคำตอบ / หาคำถามที่ยังขาด / ทวนความจำ
    # ==================================================================
    def _capture(self, state: dict, field: str, msg: str):
        data = state["data"]
        data[field] = msg
        if field == "debt":
            # ยอดผ่อนรวมต่อเดือน — ตัวตั้งของเกรด A/B/C/D และของ engine โหมด A
            data["debt_baht"] = _parse_debt_monthly(msg)
            if _says_no_debt(msg) and data["debt_baht"] is None:
                data["debt_baht"] = 0          # "ไม่มี" = ภาระ 0 ไม่ต้องถามซ้ำ
            elif data["debt_baht"] is None and not _refuses_income(msg):
                # รู้ว่ามีภาระ แต่ยังไม่ได้ตัวเลข -> ถามยอดต่อ 1 ครั้ง
                k = state.get("debt_reask", 0) + 1
                state["debt_reask"] = k
                note = (data.get("debt_note", "") + " " + msg).strip()
                if k <= DEBT_REASK_MAX:
                    data["debt_note"] = note
                    data.pop("debt", None)     # ให้ _next_missing ถามอีกรอบ
                else:
                    data["debt"] = note
                    self._add_signal(
                        state, "⚠️ มีภาระแต่ไม่ได้ยอดผ่อน/เดือน — ถามตอนโทรกลับ")
            elif data.get("debt_note"):
                # รอบสองได้ตัวเลขแล้ว -> เก็บคำตอบทั้งสองรอบไว้ให้เซลอ่านครบ
                data["debt"] = (data["debt_note"] + " " + msg).strip()
        if field == "income" and self._is_disqualified(msg):
            # รายได้ไม่ชัด -> ข้าม Q3 (บูโร) ไม่ต้องถาม ไม่ทิ้งลีด
            data["income_unknown"] = True
            data.setdefault("debt", "-")
        if field == "income" and _is_unbankable_job(msg):
            # อาชีพ/ที่มารายได้ที่ธนาคารไม่รับรอง = ยื่นเดี่ยวไม่ผ่านแน่นอน
            # ต้องเช็คก่อนดูตัวเลข เพราะ "แม่บ้าน สามีให้เดือนละ 30,000"
            # ตัวเลขผ่านเกณฑ์ แต่ไม่ใช่รายได้ของตัวเอง ธนาคารไม่นับให้
            # และต้องอยู่นอกเงื่อนไข income_unknown เพราะ "ว่างงาน" ตกอันนั้นไปแล้ว
            data["low_income"] = True
            data["income_unbankable"] = True
            data.setdefault("income_baht", _parse_income(msg) or 0)
        if (field == "income" and not data.get("income_unknown")
                and not data.get("income_unbankable") and not data.get("cash")
                and _parse_income(msg) is None):
            # ตอบมาแล้วแต่ยังไม่มีตัวเลข -> ถามใหม่แบบละมุน ครั้งเดียวเท่านั้น
            n_ask = state.get("income_reask", 0) + 1
            state["income_reask"] = n_ask
            note = (data.get("income_note", "") + " " + msg).strip()
            if _refuses_income(msg):
                # ปฏิเสธชัดเจน = หยุดทันที ไม่ว่าถามไปกี่รอบ
                data["income"] = note
                data["income_refused"] = True
                self._add_signal(state, "ลูกค้าไม่สะดวกบอกรายได้")
            elif n_ask <= INCOME_REASK_MAX:
                data["income_note"] = note     # เก็บทุกคำตอบไว้ ไม่ทิ้ง
                data.pop("income", None)       # ให้ _next_missing ถามอีกรอบ
            else:
                data["income"] = note
                self._add_signal(state, "ไม่ให้ตัวเลขรายได้ (ถาม 3 รอบแล้ว)")
        if field == "income" and not data.get("income_unknown"):
            # รายได้ต่ำกว่าเกณฑ์ยื่นเดี่ยว -> ต้องหาผู้กู้ร่วมก่อน
            # ถามผิดลำดับ = เสียเวลาทั้งสองฝ่าย เพราะยื่นเดี่ยวไม่ผ่านอยู่แล้ว
            n = _parse_income(msg)
            if n is not None and 1000 <= n < LOW_INCOME_BAHT:
                data["income_baht"] = n
                data["low_income"] = True
            # อาชีพที่ธนาคารไม่นับเป็นรายได้ประจำ = ยื่นเดี่ยวไม่ผ่านแน่นอน
            if _is_unbankable_job(msg) and (n is None or n < LOW_INCOME_BAHT):
                data["income_baht"] = n or 0
                data["low_income"] = True
                data["income_unbankable"] = True
        if field == "co_borrower":
            low = msg.lower()
            if any(h in low for h in _NO_COB_HINTS):
                data["co_borrower_none"] = True
                self._add_signal(state, "รายได้ต่ำ+ไม่มีผู้กู้ร่วม")
            else:
                # มีผู้กู้ร่วม — แต่ "มี" ไม่พอ ต้องดูว่าช่วยได้จริงไหม
                # เจอ 16 ส.ค.: รายได้ 17,000 ตอบว่า "แม่ ทำเกษตร" ระบบนับว่ามีผู้กู้ร่วม
                # แล้วเดินหน้าต่อจนได้เกรด B = เซลเสียเวลาโทรหาเคสที่แบงก์ไม่อนุมัติ
                cob_n = _parse_income(msg)
                data["co_borrower_income"] = cob_n
                weak_job = _is_unbankable_job(msg)
                total = (data.get("income_baht") or 0) + (cob_n or 0)
                data["income_total"] = total
                if weak_job or total < LOW_INCOME_BAHT:
                    data["co_borrower_weak"] = True
                    self._add_signal(
                        state,
                        "ผู้กู้ร่วมรายได้ไม่ประจำ" if weak_job
                        else f"รายได้รวม {total:,} ไม่ถึงเกณฑ์")
        state["data"] = data
        # ได้ข้อมูลใหม่ -> ส่งเข้าชีตทันที ไม่รอครบ 4 ข้อ (กันลีดหลุด)
        self._upsert_lead(state)

    def _next_missing(self, data: dict,
                      state: dict | None = None) -> tuple[str | None, str | None]:
        state = state or {}
        for f in FIELD_ORDER:
            if f == "debt" and (data.get("income_unknown") or data.get("cash")):
                continue
            if f == "income" and data.get("cash"):
                continue          # ซื้อสด = ไม่มีเหตุผลจะถามรายได้
            if f == "co_borrower" and not data.get("low_income"):
                continue          # รายได้ถึงเกณฑ์ = ยื่นเดี่ยวได้ ไม่ต้องถาม
            if f == "co_borrower" and data.get("cash"):
                continue          # ซื้อสด = ไม่ได้กู้
            if f == "contact" and state.get("contact_refused"):
                continue          # เขาบอกแล้วว่าไม่สะดวก ห้ามถามอีก
            if not data.get(f):
                if f == "income":
                    k = state.get("income_reask", 0)
                    if 1 <= k <= INCOME_REASK_MAX:
                        return f, INCOME_REASK_MSGS[k - 1]
                if f == "debt":
                    k = state.get("debt_reask", 0)
                    if 1 <= k <= DEBT_REASK_MAX:
                        return f, DEBT_REASK_MSG
                if (f == "contact"
                        and state.get("asked", {}).get("contact", 0) >= 1
                        and not state.get("contact_line_offered")):
                    # ขอเบอร์รอบแรกไปแล้วยังไม่ได้ -> รอบ 2 เปิดทาง LINE แบบนุ่มนวล
                    state["contact_line_offered"] = True
                    return f, CONTACT_REASK_MSG
                return f, QUALIFY_QUESTIONS[FIELD_Q_INDEX[f]]
        return None, None

    @staticmethod
    def _tidy(v: str) -> str:
        """ตัดคำลงท้ายสุภาพออกก่อนเอาไปทวน — กัน 'ครับ' ซ้อนกันสองที"""
        v = (v or "").strip()
        for tail in ("ครับผม", "ครับ", "ค่ะ", "คะ", "ค่า", "จ้า", "นะ"):
            while v.endswith(tail):
                v = v[: -len(tail)].strip()
        return v.strip(" .,")

    def _recap(self, data: dict) -> str:
        parts = []
        obj = self._tidy(data.get("objective", ""))
        inc = self._tidy(data.get("income", ""))
        if obj:
            parts.append(f"ลูกค้าสนใจ{obj}")
        if inc and not data.get("income_unknown"):
            parts.append(inc)
        return " ".join(parts)

