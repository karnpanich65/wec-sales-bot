    def _ask_claude(self, user_message: str, user_id: str,
                    gender: str = "",
                    done: bool = False, state: dict | None = None) -> str:
        # done=True -> ลูกค้าให้เบอร์ไปแล้ว ห้ามตอบอะไรที่เป็นการขอเบอร์ซ้ำ
        if not ANTHROPIC_API_KEY:
            return STATUS_MSG if done else FALLBACK_MSG
        history = _conversations.get(user_id, [])[-10:]
        messages = history + [{"role": "user", "content": user_message}]
        _angry = bool((state or {}).get("angry_now"))
        _smart = _angry or _needs_smart(user_message, state or {})
        _model = CLAUDE_MODEL_SMART if _smart else CLAUDE_MODEL
        _sys_prompt = (WEC_SYSTEM_PROMPT + FEMALE_VOICE_RULE
                       if gender == "female" else WEC_SYSTEM_PROMPT)
        if _angry:
            # ดับอารมณ์ต้องมาก่อนกฎอื่นเสมอ — ห้ามให้กฎ "ถามต่อ" มาชนะ
            _sys_prompt += ANGER_RULE
            state.pop("angry_now", None)
        if _smart:
            # เทิร์นที่ต้องอ่านคน — ขอให้อ่านพฤติกรรมกลับมาด้วยในคำตอบเดียวกัน
            # (ไม่ยิง API รอบสอง = ไม่มีค่าใช้จ่ายเพิ่ม) แล้วเราตัดออกก่อนส่งลูกค้า
            _sys_prompt += BEHAVIOR_READ_RULE
        try:
            resp = requests.post(
                ANTHROPIC_URL,
                headers={
                    "x-api-key": ANTHROPIC_API_KEY,
                    "anthropic-version": "2023-06-01",
                    "content-type": "application/json",
                    "anthropic-beta": "prompt-caching-2024-07-31",
                },
                json={
                    "model": _model,
                    "max_tokens": 400,
                    # prompt caching — system prompt เหมือนเดิมทุกครั้ง
                    # เปิด cache แล้วค่า input ของรอบถัดๆ ไปถูกลงมาก
                    # นี่คือตัวที่ทำให้ "ใส่ความรู้เพิ่ม" กับ "ลดค่าใช้จ่าย" ไปด้วยกันได้
                    "system": [{
                        "type": "text",
                        "text": _sys_prompt,
                        "cache_control": {"type": "ephemeral"},
                    }],
                    "messages": messages,
                },
                timeout=15,
            )
            if resp.status_code != 200:
                print(f"[CLAUDE ERROR] {resp.status_code}: {resp.text[:200]}")
                # AI ล่ม + ลูกค้าให้ข้อมูลครบแล้ว -> ห้ามถอยไปถามชุดเดิมซ้ำ
                return STATUS_MSG if done else FALLBACK_MSG
            data = resp.json()
            raw = data["content"][0]["text"].strip()
            # โดนตัดกลางประโยค -> ถอยไปจบประโยคสมบูรณ์ ไม่งั้นใช้ข้อความสำรอง
            if data.get("stop_reason") == "max_tokens":
                print(f"[CLAUDE TRUNCATED] {len(raw)} chars -> trimming")
                raw = _trim_to_sentence(raw)
                if not raw:
                    return STATUS_MSG if done else FALLBACK_MSG
            raw = self._take_behavior(raw, state, _model)
            text = self._sanitize(raw)
            text = _strip_dup_greeting(text)
            before = len(text)
            text = _limit_sentences(text)
            if before > len(text):
                print(f"[CLAUDE TRIMMED] {before} -> {len(text)} chars")
            if done and any(k in text for k in ["ขอเบอร์", "ID LINE", "เบอร์ติดต่อ"]):
                # กัน AI เผลอขอข้อมูลที่ลูกค้าให้ไปแล้ว
                return STATUS_MSG
            return text or (STATUS_MSG if done else FALLBACK_MSG)
        except Exception as e:
            print(f"[CLAUDE EXCEPTION] {e}")
            return STATUS_MSG if done else FALLBACK_MSG

    @staticmethod
    def _sanitize(text: str) -> str:
        text = _EMOJI_RE.sub("", text)
        text = text.replace("**", "").replace("###", "").replace("##", "")
        text = re.sub(r"^\s*[-*•]\s+", "", text, flags=re.MULTILINE)
        text = re.sub(r"^\s*\d+\.\s+", "", text, flags=re.MULTILINE)
        return text.strip()

