    @staticmethod
    def _is_valid_answer(field: str, msg: str) -> bool:
        """กันเก็บข้อความมั่วเป็นคำตอบ — โดยเฉพาะช่องเบอร์ติดต่อ"""
        m = msg.strip()
        if len(m) < 1:
            return False
        if field == "contact":
            low = m.lower()
            # 1) เบอร์โทร — ต้องหน้าตาเป็นเบอร์จริง ไม่ใช่แค่ "มีตัวเลขเยอะ"
            #    เจอจริง 17 ส.ค.: "ผ่อนแล้วเดือนละประมาณ 25000-30000 คับ" (10 หลัก)
            #    ผ่านเกณฑ์เดิม -> ไปโผล่ช่อง LINE ในไฟล์เซล
            if re.search(r"(?<!\d)0\d{8,9}(?!\d)", re.sub(r"[\-\s\.]", "", m)):
                return True
            _runs = re.findall(r"\d+", m)
            if (_runs and max(len(r) for r in _runs) >= 8
                    and not any(w in low for w in ("ผ่อน", "บาท", "วงเงิน",
                                                   "รายได้", "เดือนละ", "หมื่น",
                                                   "แสน", "ล้าน"))):
                return True
            # 2) บอกมาตรงๆ ว่าเป็นไลน์ / ไอดี
            if any(h in low for h in _CONTACT_HINTS):
                return True
            # 3) ID LINE ล้วนๆ เช่น "Giftdd" "gift_88" "@wealth.estate"
            #    คนไทยส่วนใหญ่พิมพ์แค่ไอดีมาเฉยๆ ไม่มีคำว่า line และไม่มีตัวเลข
            #    ของเดิมตกเคสนี้ทั้งหมด -> บอทถามซ้ำ (เจอหน้างาน 14 ส.ค. 2026)
            if (" " not in m and _LINE_ID_RE.match(m)
                    and re.search(r"[A-Za-z]", m)
                    and low.lstrip("@") not in _NOT_ID_WORDS):
                return True
            return False
        if field == "objective":
            # ต้องพูดถึงเป้าหมายจริง ไม่งั้นเก็บคำลอยๆ เป็นวัตถุประสงค์
            return any(k in m.lower() for k in _OBJECTIVE_WORDS)
        if field == "ncb":
            return (_parse_years(m) is not None
                    or _ncb_still_stuck(m) is not None
                    or _ncb_over_30(m) is not None)
        if field == "self_emp":
            # ต้องมีตัวเลขปี หรือคำตอบเรื่องภาษี/จดทะเบียน อย่างน้อย 1 อย่าง
            return (_parse_years(m) is not None) or (_parse_tax_flag(m) is not None)
        if field in ("income", "co_income", "debt", "co_debt") and _looks_like_phone(m):
            # 19 ส.ค. 2026 — เจอจริง: ลูกค้าส่งเบอร์มาตอนบอทกำลังถามยอดผ่อน
            # เบอร์ถูกเก็บเป็น "ยอดผ่อน" แล้วบอทถามยอดผ่อนซ้ำ ส่วนเบอร์หายไปเลย
            return False
        if field == "co_income":
            # ต้องมีตัวเลข หรือบอกอาชีพมา อย่างน้อย 1 อย่าง
            low = m.lower()
            if any(c.isdigit() for c in m):
                return True
            return any(k in low for k in _INCOME_WORDS) or _is_unbankable_job(m)
        if field == "co_debt":
            # ตัวเลขยอดผ่อน หรือบอกว่า "ไม่มี"
            return (_parse_debt_monthly(m) is not None
                    or _says_no_debt(m)
                    or any(c.isdigit() for c in m))
        if field == "income":
            # กันเก็บข้อความมั่วเป็นรายได้ — เจอจริง 14 ส.ค. เก็บคำว่า "รูปแบบ"
            # เป็นรายได้ลูกค้า แล้วเดินหน้าถามข้อถัดไปเหมือนไม่มีอะไรเกิดขึ้น
            low = m.lower()
            if any(c.isdigit() for c in m):
                return True
            return any(k in low for k in _INCOME_WORDS)
        return True

    # ==================================================================
    # FAQ / Trigger / Disqualify  (เหมือนเดิม)
