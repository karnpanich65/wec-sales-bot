    def handle_page_echo(self, customer_id: str, text: str,
                         platform: str = "facebook", page_id: str = "",
                         from_app: bool = False) -> str:
        """ข้อความที่ "เพจ" ส่งออก (echo) — ใช้ตรวจว่าเซลเข้ามาคุยเองหรือยัง

        from_app=True  -> บอทเป็นคนส่งเอง ไม่ต้องทำอะไร
        from_app=False -> คนพิมพ์จากกล่องข้อความเพจ
        คืนค่า: 'handover' | 'resume' | 'logged' | 'skip'
        """
        if from_app:
            return "skip"
        skey = f"{page_id}:{customer_id}" if page_id else customer_id
        state = _lead_states.get(skey) or self._load_session(customer_id, page_id) or {}
        if not state:
            state = {"data": {}, "signals": [], "asked": {}}
        state.setdefault("data", {})
        state["platform"] = platform
        if page_id:
            state["page_id"] = page_id
        result = "logged"
        if _is_resume_trigger(text):
            state["handover"] = False
            state["handover_ended_at"] = _now()
            result = "resume"
            self._resume_context(customer_id, state)
            print(f"[HANDOVER OFF] {customer_id[:8]}... กลับมาให้บอทตอบ")
        elif not state.get("handover"):
            # 19 ส.ค. 2026 (Gift): เดิมต้องมีคำทักทาย + ชื่อเซล ถึงจะหยุดบอท
            # เคสจริง: เซลพิมพ์ "พี่เจี๊ยบเองค่ะ" -> ไม่เข้าเงื่อนไข -> บอทตอบแทรกต่อ
            # กติกาใหม่: มีคนพิมพ์เองจากกล่องข้อความเพจ = รับช่วงทันที ทุกข้อความ
            state["handover"] = True
            state["handover_at"] = _now()
            result = "handover"
            state["handover_log"] = []
            _who = _who_greeted(text, page_id) or _who_typed(text, page_id)
            if _who:
                state["handover_by"] = _who
            self._add_signal(
                state,
                (f"เซล{_who} " if _who else "เซล")
                + f"เข้ารับช่วงคุยเอง — บอทหยุดตอบแชทนี้ {HANDOVER_DAYS} วัน")
            print(f"[HANDOVER ON] {customer_id[:8]}... "
                  f"เซล{_who or '(ไม่ระบุชื่อ)'} รับช่วงแล้ว | {text[:40]!r}")
        if state.get("handover"):
            self._handover_note(state, "sale", text)
        _lead_states[skey] = state
        # เก็บข้อความของเซลลง Chat_Log ด้วย (ไม่ให้ log ขาดช่วง)
        try:
            self._persist(customer_id, state, "", "[เซล] " + (text or ""), "live")
        except Exception as e:
            print(f"[HANDOVER PERSIST ERROR] {e}")
        return result

    @staticmethod
    def _handover_note(state: dict, who: str, text: str):
        """เก็บบทสนทนาช่วง "เซลดูแลเอง" ไว้ใน state

        state ก้อนนี้ถูก persist ลงชีตทุกครั้ง -> restart/deploy ก็ยังอยู่
        ครบ 3 วันบอทกลับมา จึงอ่านต่อได้ว่าคุยอะไรค้างไว้ ไม่ต้องเริ่มใหม่
        """
        t = (text or "").strip()
        if not t:
            return
        log = list(state.get("handover_log") or [])
        log.append({"w": who, "t": t[:300]})
        state["handover_log"] = log[-HANDOVER_LOG_MAX:]

    def _resume_context(self, user_id: str, state: dict):
        """โหลดบทสนทนาช่วงเซลคุย กลับเข้าความจำของบอท (ตอนหมดเวลา 3 วัน)

        ทำเฉพาะตอนความจำใน RAM ว่าง (เพิ่ง restart) — ถ้ายังมีอยู่ ไม่ต้องยุ่ง
        รวมท่อนที่ role ซ้ำกันติดกันเป็นก้อนเดียว เพราะ Claude API
        ต้องการ user/assistant สลับกัน ไม่งั้น 400
        """
        log = state.get("handover_log") or []
        if not log or _conversations.get(user_id):
            return
        msgs: list[dict] = []
        for it in log:
            role = "user" if it.get("w") == "cust" else "assistant"
            txt = (it.get("t") or "").strip()
            if not txt:
                continue
            if role == "assistant":
                txt = f"[เซล] {txt}"
            if msgs and msgs[-1]["role"] == role:
                msgs[-1]["content"] += "\n" + txt
            else:
                msgs.append({"role": role, "content": txt})
        msgs = msgs[-10:]
        while msgs and msgs[0]["role"] != "user":
            msgs.pop(0)
        if msgs:
            _conversations[user_id] = msgs
            print(f"[HANDOVER CTX] {user_id[:8]}... "
                  f"ต่อบทสนทนาเก่า {len(msgs)} ท่อน")

    def _ensure_fb_name(self, user_id: str, state: dict):
        """ดึงชื่อลูกค้าครั้งเดียวต่อ session แล้วเก็บไว้ใน state

        กติกาที่ทำให้ไม่พัง:
        - ยิง background thread -> ไม่บล็อกการตอบลูกค้า (Graph timeout 5 วิ)
        - ยิงสูงสุด 2 ครั้งต่อ session (`fb_name_tries`) -> token ล่มชั่วคราวยังมีโอกาสที่ 2
          แต่ไม่ยิงรัวทุกข้อความจนโดน Graph rate limit
        - ได้ชื่อแล้วจำใน state และ state ถูก persist ลงชีต -> restart ไม่ต้องยิงใหม่
        - ยิงไม่ได้เลย -> ใส่ "(ยังไม่ได้ชื่อ)" ให้เห็นในชีตว่าเป็นปัญหา token
          ไม่ใช่ปล่อยว่างจนแยกไม่ออกจาก "ยังไม่ได้ยิง"
        """
        if state.get("fb_name"):
            return
        if state.get("fb_name_tries", 0) >= 2:
            return
        state["fb_name_tries"] = state.get("fb_name_tries", 0) + 1
        platform = state.get("platform", "facebook")
        page_id = state.get("page_id", "")

        def _work():
            try:
                nm = self._get_fb_name(user_id, platform, page_id)
                if nm and not state.get("chat_name"):
                    # ชื่อที่ลูกค้าพิมพ์เองสำคัญกว่าชื่อโปรไฟล์ -> ห้ามทับ
                    state["fb_name"] = nm
                    print(f"[NAME] {user_id[:8]}... = {nm}")
                elif state.get("fb_name_tries", 0) >= 2 and not state.get("fb_name"):
                    # ครบ 2 ครั้งแล้วยังไม่ได้ = บอกให้รู้ ไม่ปล่อยว่างเงียบ
                    state["fb_name"] = "(ยังไม่ได้ชื่อ)"
                    print(f"[NAME MISS] {user_id[:8]}... ยิงครบ 2 ครั้งแล้วไม่ได้ชื่อ "
                          f"— เช็ค token ของเพจ {page_id or '(ไม่รู้เพจ)'}")
            except Exception as e:
                print(f"[NAME BG ERROR] {e}")

        threading.Thread(target=_work, daemon=True,
                         name=f"wec-name-{user_id[:6]}").start()

    def _get_fb_name(self, user_id: str, platform: str = "facebook",
                     page_id: str = "") -> str:
        # 17 ส.ค. 2026 — บั๊กตัวจริงของ "ชื่อว่าง 97%":
        # PSID เป็น page-scoped -> อ่านชื่อได้ด้วย token ของ "เพจที่ลูกค้าทัก" เท่านั้น
        # ของเดิมใช้ FB_PAGE_ACCESS_TOKEN ตัวเดียวกับทุกเพจ -> Graph ตอบ error เงียบๆ
        #
        # อัปเดตรอบ 2 (คืนเดียวกัน) — log production จับได้ว่า PAGE_TOKEN_<id>
        # บางตัว "ส่งข้อความได้แต่อ่านชื่อไม่ได้" (Graph 100 missing permissions —
        # token ที่ generate ผ่าน Graph API Explorer 16 ส.ค. สิทธิ์ไม่ครบ)
        # ขณะที่ FB_PAGE_ACCESS_TOKEN ตัวเก่าอ่านชื่อได้ (มี 3 ชื่อในชีตเป็นหลักฐาน)
        # -> ต้องลองทีละ token: ตัวของเพจก่อน แล้วถอยไปตัวกลาง ตัวไหนได้ใช้ตัวนั้น
        # + log บอกว่าตัวไหนเวิร์ก จะได้รู้ว่า token ตัวไหนต้อง generate ใหม่
        cands = []
        if page_id:
            t = os.environ.get(f"PAGE_TOKEN_{page_id}", "").strip()
            if t:
                cands.append((f"PAGE_TOKEN_{page_id}", t))
        if FB_PAGE_ACCESS_TOKEN and all(t != FB_PAGE_ACCESS_TOKEN for _, t in cands):
            cands.append(("FB_PAGE_ACCESS_TOKEN", FB_PAGE_ACCESS_TOKEN))
        if not cands:
            return ""
        # Messenger User Profile API รองรับ first_name/last_name เป็นทางการ
        # (ขอ "name" เฉยๆ บางแอปโดนปัด) — IG ใช้ name,username ตามเดิม
        fields = ("name,username" if platform == "instagram"
                  else "first_name,last_name")
        for src, token in cands:
            try:
                resp = requests.get(
                    f"{FB_GRAPH_URL}/{user_id}",
                    params={"fields": fields, "access_token": token},
                    timeout=5,
                )
                j = resp.json()
                if "error" in j:
                    err = j["error"]
                    print(f"[NAME ERROR] ({platform}) page={page_id or '-'} "
                          f"via {src} Graph {err.get('code')}: "
                          f"{str(err.get('message', ''))[:100]}")
                    continue          # token นี้ไม่ได้ -> ลองตัวถัดไป
                if platform == "instagram":
                    nm = j.get("name") or j.get("username") or ""
                else:
                    nm = " ".join(x for x in (j.get("first_name", ""),
                                              j.get("last_name", "")) if x).strip()
                    nm = nm or j.get("name", "")
                if nm:
                    if src != cands[0][0]:
                        # ตัวแรกพัง ตัวถอยเวิร์ก -> บอกไว้ใน log ให้รู้ว่า
                        # PAGE_TOKEN_<id> ตัวนั้นควร generate ใหม่ (แต่ระบบยังเดินต่อได้)
                        print(f"[NAME OK-FALLBACK] page={page_id or '-'} "
                              f"ได้ชื่อจาก {src} — {cands[0][0]} อ่านชื่อไม่ได้ "
                              f"ควร generate token ใหม่")
                    return nm
            except Exception as e:
                print(f"[NAME ERROR] ({platform}) page={page_id or '-'} via {src} {e}")
        return ""

