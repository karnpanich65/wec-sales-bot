_PERSIST_Q: "queue.Queue[dict]" = queue.Queue(maxsize=500)


def _persist_worker():
    while True:
        payload = _PERSIST_Q.get()
        try:
            if APPS_SCRIPT_URL:
                r = requests.post(APPS_SCRIPT_URL, json=payload, timeout=15)
                if r.status_code != 200:
                    print(f"[PERSIST] HTTP {r.status_code} {r.text[:120]}")
        except Exception as e:
            print(f"[PERSIST ERROR] {e}")
        finally:
            _PERSIST_Q.task_done()


threading.Thread(target=_persist_worker, daemon=True, name="wec-persist").start()


def _enqueue(payload: dict):
    """ยิงงานเขียนเข้าคิว — ถ้าคิวเต็มก็ทิ้ง ดีกว่าทำให้บอทค้าง"""
    if not (FEATURE_PERSIST and APPS_SCRIPT_URL):
        return
    try:
        _PERSIST_Q.put_nowait(payload)
    except queue.Full:
        print("[PERSIST] queue full — dropped")


def _hash_psid(psid: str) -> str:
    return hashlib.sha256((PSID_SALT + psid).encode()).hexdigest()[:12]


def _now() -> int:
    return int(time.time())


class BotEngine:
    # ==================================================================
    # Entry point
    # ==================================================================
    @staticmethod
    def rekey(old_key: str, new_key: str, new_psid: str = ""):
        """ย้าย state จากคีย์ชั่วคราวไปคีย์จริง

        ใช้กับคอมเมนต์: ตอนประมวลผลเรายังไม่รู้ PSID ของคนคอมเมนต์
        Facebook ไม่ให้เอา id ของคนคอมเมนต์ไปส่งข้อความตรงๆ
        จะรู้ PSID ก็ต่อเมื่อยิง Private Reply สำเร็จ แล้ว API คืน recipient_id มา
        """
        if old_key == new_key or old_key not in _lead_states:
            return
        st = _lead_states.pop(old_key)
        if new_psid:
            st["psid"] = new_psid
        _lead_states[new_key] = st
        conv = _conversations.pop(old_key, None)
        if conv is not None:
            _conversations[new_key] = conv

    @staticmethod
    def drop(key: str):
        """ทิ้ง state ที่สร้างไว้แล้วใช้ไม่ได้ (เช่นส่ง Private Reply ไม่สำเร็จ)"""
        _lead_states.pop(key, None)
        _conversations.pop(key, None)

    def process(self, user_message: str, user_id: str,
                referral: dict | None = None,
                platform: str = "facebook",
                page_id: str = "", brand: str = "",
                sheet_tab: str = "", gender: str = "") -> tuple[str, str | None]:
        """คืนค่า (ข้อความตอบ, grade หรือ None)

        ข้อความตอบอาจมี MSG_SPLIT คั่น -> main.py แยกส่งเป็นหลายบับเบิล
        """
        referral = referral or {}
        skey = f"{page_id}:{user_id}" if page_id else user_id
        state, is_new = self._resolve_state(user_id, platform, referral,
                                            skey, page_id)

        gap = _now() - state.get("last_seen", _now())
        bucket = self._gap_bucket(gap) if not is_new else "new"
        state["last_seen"] = _now()
        state["platform"] = platform
        # บริบทเพจ — คนละเพจ = คนละแบรนด์ คนละแท็บชีต (PSID ของ FB ผูกกับเพจ)
        if page_id:
            state["page_id"] = page_id
        if brand:
            state["brand"] = brand
        if sheet_tab:
            state["sheet_tab"] = sheet_tab
        if gender:
            state["gender"] = gender
        if referral:
            state["referral"] = referral

        # 17 ส.ค. 2026 — ดึงชื่อลูกค้าตั้งแต่ข้อความแรก ไม่รอปิดเคส
        # บั๊กเดิม: _get_fb_name ถูกเรียกที่เดียวคือใน _finish() -> ลีดที่คุยค้าง
        # / ไม่ให้เบอร์ / หายกลางทาง มีแถวในชีตแต่ "ช่องชื่อว่างตลอดไป"
        # ตรวจ CRM จริง 17 ส.ค. 2026: 145 ลีด มีชื่อแค่ 5 แถว (3%)
        # ยิงใน background thread เพราะ Graph API timeout 5 วิ ห้ามบล็อกการตอบลูกค้า
        self._ensure_fb_name(user_id, state)

        bubbles, grade = self._decide(user_message, user_id, state, bucket, is_new)

        parts = [b for b in bubbles if b and b.strip()]
        if state.get("gender") == "female":
            parts = [to_female(p) for p in parts]
        reply = MSG_SPLIT.join(parts)
        self._log(user_id, user_message, reply)
        self._persist(user_id, state, user_message, reply, bucket)
        return reply, grade

    # ==================================================================
    # ตัดสินใจว่าจะตอบอะไร — หัวใจของ Phase 4
    # ==================================================================
    def _decide(self, msg: str, user_id: str, state: dict,
                bucket: str, is_new: bool) -> tuple[list[str], str | None]:
        data = state["data"]
        awaiting = state.get("awaiting")
        bubbles: list[str] = []
        grade = None

        # ---- 1) เปิดหัวข้อความตามระยะที่หายไป -------------------------
        # ข้อความแรกที่เป็นคำถามจริง -> ไม่ต้องทักทาย ตอบคำถามเขาเลย
        # เจอ 15 ส.ค.: คนตอบกลับโฆษณาได้ข้อความทักทายไปแล้ว 1 ครั้ง
        # พอเขาถามต่อ ระบบทักซ้ำอีก + ตอบ + ถาม = 3 บับเบิล ทักทาย 2 รอบ
        # อ่านแล้วเหมือนบอทค้าง ไม่เหมือนคนคุย
        if is_new and not self._is_question(msg):
            bubbles.append(self._welcome(state))
        elif bucket == "cold" and data:
            # หายไปเกิน 1 วัน + เคยให้ข้อมูลไว้ -> ทวนให้ฟังว่าเราจำได้
            recap = self._recap(data)
            if recap:
                bubbles.append(RETURNING_MSG.format(recap=recap))

        # ---- 2) ลูกค้าพูดอะไร ตอบอันนั้นก่อนเสมอ ----------------------
        # ถ้ากำลังรอคำตอบอยู่ แต่ลูกค้าดันถามคำถามกลับมา
        # ห้ามเอาคำถามของเขาไปนับเป็นคำตอบ — ตอบเขาก่อน แล้วค่อยถามใหม่
        # ---- 1.5) อ่านเจตนาพิเศษก่อนอย่างอื่น (Phase 4.3) --------------
        state["turns"] = state.get("turns", 0) + 1
        self._scan_signals(state, msg)

        # ธงอาชีพอิสระ/ไม่มีประกันสังคม — ติดครั้งเดียว ไม่ตัดเกรด
        if not state.get("self_employed") and _is_self_employed(msg):
            state["self_employed"] = True
            self._add_signal(
                state,
                "อาชีพอิสระ/ไม่มีประกันสังคม — ต้องใช้ statement ย้อนหลัง 6-12 ด. "
                "เอกสารมากกว่าเคสพนักงานประจำ อย่าเพิ่งฟันว่าผ่าน",
            )

        # เจ้าของห้องอยู่แล้ว แต่ตั้งใจ "ซื้อเพิ่ม" -> อยู่สายนักลงทุนตามเดิม
        # แค่ติดธงให้เซลรู้ว่าคนนี้กู้ผ่านมาแล้ว = โอกาสปิดสูงกว่าคนทักเปล่าๆ
        if not state.get("owner_has_unit"):
            _f = _owner_flags(msg)
            if _f["have"] and (_f["buy"] or _f["rentout"]):
                state["owner_has_unit"] = True
                _note = "มีห้อง/คอนโดอยู่แล้ว"
                if _f["recent"]:
                    _note += " และเพิ่งซื้อ/เพิ่งโอน = กู้ผ่านมาแล้ว"
                self._add_signal(state, _note + " — ลูกค้าเก่าของตลาด ปิดง่ายกว่า")

        # ก) ลูกค้าปฏิเสธการถูกโทร -> ยอมรับทันที ห้ามขอช่องทางซ้ำ
        #    เขาไม่ได้ปฏิเสธเรา เขาปฏิเสธ "การถูกโทร" ซึ่งเราพูดขึ้นมาเอง
        if not state.get("done") and self._is_refusal(msg, awaiting):
            # ไม่ให้เบอร์ (แต่ยังไม่ได้ห้ามโทร) + ยังไม่เคยเสนอ LINE
            # -> เสนอ LINE 1 ครั้งแบบนุ่มนวล ยังไม่ยอมแพ้ (Gift สั่ง 17 ส.ค.)
            if (awaiting == "contact" and _refuses_phone_only(msg)
                    and not state.get("contact_line_offered")):
                state["contact_line_offered"] = True
                state["awaiting"] = "contact"
                self._add_signal(state, "ไม่ให้เบอร์รอบแรก — เสนอ LINE แทน")
                self._upsert_lead(state)
                bubbles.append(CONTACT_REASK_MSG)
                return bubbles, None
            state["contact_refused"] = True
            state["awaiting"] = None
            self._upsert_lead(state)
            bubbles.append(CONTACT_REFUSED_MSG)
            return bubbles, None

        # ข) ซื้อเงินสด -> หยุดถามเรื่องกู้ทั้งชุด แล้วชวนดูห้องจริง
        #    คนถือเงินสดจริงไม่มีทางโอนโดยไม่เห็นของ = ด่านที่ฟรีสำหรับคนจริง
        if not state.get("done") and self._is_cash(msg) and not data.get("cash"):
            data["cash"] = True
            data.setdefault("income", "ซื้อเงินสด")
            data.setdefault("debt", "-")
            state["awaiting"] = None
            state["cash_invited"] = True
            self._upsert_lead(state)
            bubbles.append(CASH_BUYER_MSG)
            bubbles.append(CASH_INVITE_MSG)
            return bubbles, None

        # ข.1.5) เจ้าของห้องมาฝากปล่อยเช่า/ฝากขาย -> คนละสายกับนักลงทุน
        #        ต้องเช็คก่อนสายผู้เช่า เพราะ "ฝากขาย" ไม่มีคำว่าเช่าเลย
        if (not state.get("done") and not state.get("owner")
                and not state.get("renter") and _is_owner_listing(msg)):
            f = _owner_flags(msg)
            sell_only = f["sell"] and not f["rentout"]
