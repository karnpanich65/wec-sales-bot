        # ข.1.6) อยู่ในสายเจ้าของแล้ว -> เก็บ 4 ข้อ ทีละข้อ ขอช่องทางติดต่อก่อน
        if (state.get("owner") and not state.get("done")
                and awaiting in OWNER_FIELDS and not self._is_question(msg)):
            data[awaiting] = msg
            state["data"] = data
            i = OWNER_FIELDS.index(awaiting)
            if i + 1 < len(OWNER_FIELDS):
                nxt = OWNER_FIELDS[i + 1]
                state["awaiting"] = nxt
                self._upsert_lead(state)
                bubbles.append(OWNER_Q[nxt])
                return bubbles, None
