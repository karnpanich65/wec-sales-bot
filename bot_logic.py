    def _log(self, user_id: str, user_msg: str, reply: str):
        h = _conversations.get(user_id, [])
        h.append({"role": "user", "content": user_msg})
        h.append({"role": "assistant", "content": reply.replace(MSG_SPLIT, "\n")})
        if len(h) > 20:
            h = h[-20:]
        _conversations[user_id] = h


