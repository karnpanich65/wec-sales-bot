    def _finish(self, user_id: str, state: dict, contact: str,
                calendar: bool = True) -> str:
        """ปิดเคส -> คิดเกรด + เขียนแถวสมบูรณ์ลงชีต
        calendar=False -> ลงชีตอย่างเดียว ไม่สร้างนัดโทรกลับ
                          (เคสที่ไม่มีช่องทางติดต่อ เช่น ไม่มีผู้กู้ร่วม)
        ทางเข้าปิดเคส "ทุกทาง" ต้องผ่านฟังก์ชันนี้ ห้ามเขียนซ้ำที่อื่น
        ไม่งั้นจะตกอย่างใดอย่างหนึ่งเสมอ (เคยตก lead_sent + fb_name มาแล้ว)
        """
        data = state["data"]
        if state.get("owner"):
            grade = "O"           # เจ้าของห้องฝากงาน — ไม่ใช่ลีดซื้อ ไม่ตีเกรดกู้
        elif state.get("renter"):
            grade = "R"           # ผู้เช่า — คนละกลุ่ม ไม่เข้าเกณฑ์ A/B/C/D
        elif data.get("income_unknown") or data.get("co_borrower_none"):
            grade = "C"           # ยื่นเดี่ยวไม่ผ่าน = ยังไม่ใช่คิวโทรด่วน
        else:
            grade = self._grade(data, state)
        state["score"] = self._intent_score(state)
        data["score"] = state["score"]
        # เหตุผลของเกรด ให้เซลเห็นในชีต (คอลัมน์สัญญาณ) — ห้ามส่งให้ลูกค้า
        if grade == "O":
            data["income"] = f"ค่าเช่า/ราคาที่ต้องการ {self._tidy(data.get('own_rent', '-'))}"
            data["debt"] = (f"โครงการ {self._tidy(data.get('own_project', '-'))} · "
                            f"ห้อง {self._tidy(data.get('own_detail', '-'))}")
            self._add_signal(state, "ไม่ใช่ลีดซื้อ — ห้ามนับรวมยอดขาย")
        if grade == "R":
            # ผู้เช่า — ยัดรายละเอียดลงช่องที่ชีตมีอยู่แล้ว ไม่ต้องแก้ Apps Script
            data["income"] = f"งบค่าเช่า {self._tidy(data.get('rent_budget', '-'))}"
            data["debt"] = (f"ทำเล {self._tidy(data.get('rent_zone', '-'))} · "
                            f"เข้าอยู่ {self._tidy(data.get('move_in', '-'))}")
            self._add_signal(state, "ผู้เช่า (ไม่ใช่นักลงทุน) — ทีมห้องเช่ารับช่วง")
        if grade == "D":
            self._add_signal(state, "ภาระหนัก (ผ่อนเกินรายได้) — เคสบริดจ์ ดูแผนปิดหนี้ก่อน")
        if grade == "N":
            self._add_signal(state, "⚠️ ยังไม่ได้ตัวเลขรายได้ — โทรถามก่อนตีเกรด")
        cap_now, cap_clear = data.get("capacity_now"), data.get("capacity_clear")
        if cap_now is not None:
            d_baht = data.get("debt_baht")
            if d_baht:
                self._add_signal(state, f"ผ่อน/เดือน {d_baht:,}")
            elif d_baht == 0:
                self._add_signal(state, "ไม่มีภาระผ่อน")
            else:
                # ลูกค้าบอกว่ามีหนี้แต่ไม่ให้ยอด -> คิดวงเงินแบบไม่มีภาระไว้ก่อน
                # (ห้ามฝังลีดดีเพราะข้อมูลขาด) แต่ต้องติดธงให้เซลถามตอนโทร
                self._add_signal(state, "⚠️ ยังไม่ได้ยอดผ่อน/เดือน — เกรดยังไม่ยืนยัน")
            self._add_signal(state, f"วงเงินตอนนี้ {cap_now/1e6:.1f}M")
            if grade == "B":
                self._add_signal(state, f"ปิดภาระแล้วได้ {cap_clear/1e6:.1f}M = เคสบริดจ์")
        state["done"] = True
        state["awaiting"] = None
        data["grade"] = grade
        # หมายเหตุ 17 ส.ค. 2026 (Gift): ด่านแรกคัดหยาบ ห้ามตัดสินเคส
        # เดิม D ไม่นัดโทร -> เกือบทิ้งเคสบริดจ์ชั้นดี
        # (เคสจริง DSR 75% วงเงิน 0 แต่ปิดบัตรก้อนเดียว = วงเงิน 4.69 ล้าน)
        # D จึงแปลว่า "ต้องดูแผนปิดหนี้ก่อน" ไม่ใช่ "ไปไม่ได้" -> นัดโทรปกติ
        # 17 ส.ค. 2026 — ใช้ชื่อที่ _ensure_fb_name ดึงไว้แล้วก่อน
        # ยิง Graph ซ้ำเฉพาะตอนที่ยังไม่มีจริงๆ (ประหยัดโควตา + ไม่หน่วงตอนปิดเคส)
        fb_name = state.get("fb_name") or ""
        if not fb_name or fb_name == "(ยังไม่ได้ชื่อ)":
            fb_name = self._get_fb_name(user_id, state.get("platform", "facebook"),
                                        state.get("page_id", "")) or fb_name
        state["fb_name"] = fb_name
        # ส่งชุดเต็ม (แถวสมบูรณ์ + สร้างนัดในปฏิทิน) — schema เดิม ไม่แตะ
        self._send_to_sheets(user_id, data, grade, fb_name,
                             state.get("referral", {}),
                             state.get("platform", "facebook"),
                             state.get("page_id", ""),
                             state.get("sheet_tab", ""),
                             signals=state.get("signals", []),
                             contact_refused=state.get("contact_refused", False),
                             calendar=calendar)
        state["lead_sent"] = True
        return grade

    def _grade(self, data: dict, state: dict | None = None) -> str:
        """เกรดลีดตามกำลังกู้จริง (Gift เคาะ 16 ส.ค. 2026)

        A = กู้ได้เลย ไม่ต้องปิดภาระ
        B = ปิดหนี้ก่อน แล้วกู้ได้ 1 ห้อง  (เคสบริดจ์ = งานหลักของ WEC)
        C = DSR ไม่เกิน 100%
        D = DSR เกิน 100%
        อ่านไม่ออก (ไม่รู้รายได้) -> C ไว้ก่อน ให้คนเช็ค ไม่ทิ้งลีด
        """
        income = (data.get("income_total") or data.get("income_baht")
                  or _parse_income(str(data.get("income", ""))))
        if not income or data.get("income_unknown"):
            # ไม่มีตัวเลขรายได้ = คำนวณวงเงินไม่ได้
            # สายซื้อเงินสดที่จริงจังมาก (ยอมนัดดูห้อง ฯลฯ) ยังขึ้น A ได้เหมือนเดิม
            if state is not None and self._intent_score(state) >= 6:
                return "A"
            # ที่เหลือ = "N ข้อมูลไม่พอ" ไม่ใช่ C (Gift เคาะ 16 ส.ค. 2026)
            # C แปลว่า "คำนวณแล้วยังไม่ไหว" · N แปลว่า "ยังคำนวณไม่ได้ ต้องโทรถาม"
            # ห้ามปนกัน ไม่งั้นลีดดีที่แค่ไม่บอกตัวเลขจะจมไปกับเคสที่ไปต่อไม่ได้
            return "N"

        debt = data.get("debt_baht")
        if debt is None:
            debt = _parse_debt_monthly(str(data.get("debt", "")))
        debt = 0 if debt is None else max(0, int(debt))

        cap_now = _capacity(income, debt)
        cap_clear = _capacity(income, 0)
        # เก็บไว้ให้เซล/ชีตเห็นเหตุผลของเกรด (ห้ามส่งให้ลูกค้า)
        data["capacity_now"] = cap_now
        data["capacity_clear"] = cap_clear

        if cap_now >= UNIT_PRICE_BAHT:
            return "A"
        if cap_clear >= UNIT_PRICE_BAHT:
            return "B"          # ปิดภาระแล้วไปได้ = ลีดของทีมบริดจ์
        if debt <= income:      # DSR <= 100%
            return "C"
        return "D"

