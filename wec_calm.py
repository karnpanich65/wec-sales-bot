def detect_stop(text: str) -> int:
    """0 = ปกติ · 1 = บอทตอบไม่เข้าท่า · 2 = ลูกค้าสั่งเลิกติดต่อ

    ยอมพลาดฝั่ง "หยุดเร็วไป" ดีกว่าพลาดฝั่ง "พูดทับคนที่สั่งให้เงียบ"
    """
    t = (text or "").strip()
    if not t:
        return 0
    low = t.lower()
    for _safe in _ANGER_EXEMPT:
        low = low.replace(_safe, " ")
    if any(w in low for w in _STOP_HARD):
        return 2
    if any(w in low for w in _STOP_SOFT):
        return 1
    return 0


# ระดับ 2 — ปิดท้ายให้จบสวย ไม่ขายต่อ ไม่ทิ้งคำถาม เปิดประตูไว้เฉยๆ
