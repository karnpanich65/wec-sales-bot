_ANGER_EXEMPT = ("สะพานควาย", "เงินหายาก", "แม่งาน")

CALM_COOLDOWN_SEC = 3600      # ปลุกคนซ้ำได้ทุก 1 ชม. ไม่รัวกว่านั้น


def detect_anger(text: str) -> int:
    """0 = ปกติ · 1 = หงุดหงิด/ถามเรื่องเงินคืน · 2 = ร้องเรียน/อารมณ์แรง

    ตั้งใจให้ตื่นง่ายไว้ก่อน — ทางลงของการจับเกินคือมีคนโทรไปคุยแล้วพบว่า
    ไม่มีอะไร ส่วนทางลงของการปล่อยหลุดคือลูกค้าโกรธแล้วไม่มีใครรู้เลย
    """
    t = (text or "").strip()
    if not t:
        return 0
    low = t.lower()
    for _safe in _ANGER_EXEMPT:
        low = low.replace(_safe, " ")
    if any(w in low for w in _ANGER_HARD) or any(w in low for w in _ANGER_RUDE):
        return 2
    if any(w in low for w in _ANGER_SOFT):
        return 1
    # เครื่องหมายตกใจรัวๆ พร้อมข้อความยาว = คนกำลังระบาย ไม่ใช่ถามข้อมูล
    if t.count("!") >= 3 and len(t) >= 25:
        return 1
    return 0


def calm_mode(engine, user_id: str, state: dict,
              user_message: str, level: int):
    """คืน (ข้อความตอบ, ธงปลุกคน)

    ธง "!"  -> main.py ยิงแจ้งเตือนหาเจ้าของเพจ (ตกมาที่ Gift ถ้าเพจไม่ได้ตั้ง)
    ธง None -> ปลุกไปแล้วในรอบนี้ เงียบไว้ ปล่อยให้คนที่รับเรื่องคุยต่อ
    """
    now = int(time.time())
    first = not state.get("angry")
    state["angry"] = True
    state["angry_level"] = max(int(state.get("angry_level") or 0), int(level))
    state["angry_at"] = now

    # ธงลงชีต — โผล่ในคอลัมน์สัญญาณเหมือนธงตัวอื่นทุกตัว ไม่ต้องแก้ Apps Script
    sig = "🔴 เคสร้องเรียน" if level >= 2 else "⚠️ ลูกค้าไม่พอใจ"
    sigs = state.setdefault("signals", [])
    if sig not in sigs:
        sigs.append(sig)

    # ส่งให้คนดูแลทันที และล็อกไม่ให้บอทวนกลับไปขายต่อเอง
    state["handover"] = True
    state["handover_at"] = now
    state["handover_sale_at"] = now
    state["handover_by"] = "(เคสร้องเรียน — รอผู้จัดการ)"

    # ให้มีแถวในชีตทันที ไม่ต้องรอปิดเคส — คนโกรธมักไม่ตอบคำถามต่อ
    try:
        engine._upsert_lead(state)
    except Exception as _e:
        print(f"[CALM UPSERT] {_e}")

    _last = int(state.get("angry_alert_at") or 0)
    wake = first or (now - _last) >= CALM_COOLDOWN_SEC
    if wake:
        state["angry_alert_at"] = now

    print(f"[ANGRY] {user_id[:8]}... ระดับ {level} "
          f"page={state.get('page_id') or '-'} "
          f"{'ปลุกคน' if wake else 'ปลุกไปแล้ว รอบนี้เงียบ'} "
          f"| {user_message[:60]!r}")

    flag = "!" if wake else None

    # แชทที่เซลสั่งปิดบอทถาวร = มีคนดูแลอยู่แล้ว ปลุกอย่างเดียว ไม่พิมพ์แทรก
    # และถ้าเคยดับอารมณ์ไปแล้วในรอบนี้ ก็ไม่พิมพ์ซ้ำให้รำคาญ
    if state.get("bot_off") or not first:
        return "", flag

    if level >= 2:
        msg = ("รับเรื่องแล้วครับ ต้องขออภัยจริงๆ กับสิ่งที่เกิดขึ้น "
               "ผมส่งเรื่องให้ผู้จัดการแล้วนะครับ "
               "รบกวนขอชื่อ-นามสกุล เบอร์ติดต่อ และเวลาที่สะดวก "
               "จะให้โทรกลับหาคุณโดยตรงครับ")
    else:
        msg = ("ขอส่งเรื่องนี้ให้ที่ปรึกษาดูแลโดยตรงนะครับ "
               "รบกวนขอชื่อกับเบอร์ติดต่อ และเวลาที่สะดวก "
               "แล้วจะให้โทรกลับไปคุยกับคุณครับ")

    if state.get("gender") == "female":
        try:
            from bot_logic import to_female     # ยืมตัวแปลงเดิม เลี่ยง import วน
            msg = to_female(msg)
        except Exception as _e:
            print(f"[CALM FEMALE] {_e}")
    return msg, flag
