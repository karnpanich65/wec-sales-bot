def stop_mode(engine, user_id: str, state: dict, user_message: str, level: int = 2):
    """คืน (ข้อความปิดท้าย, ธงปลุกคน)

    ระดับ 2 = ปิดบอทถาวรสำหรับแชทนี้ (ปลดด้วย #เปิดบอท)
    ระดับ 1 = แค่เงียบ + ส่งต่อคน ยังไม่ปิดถาวร เผื่อคนเข้าไปกู้เคสทัน
    ครั้งแรกเท่านั้นที่พูด — ครั้งต่อไปเงียบสนิท
    """
    now = int(time.time())
    first = not state.get("stopped")
    state["stopped"] = True
    state["stopped_at"] = now
    state["stop_level"] = max(int(state.get("stop_level") or 0), int(level))
    if level >= 2:
        state["bot_off"] = True                  # r64 — ปิดถาวร ปลดด้วย #เปิดบอท
    state["handover"] = True
    state["handover_at"] = now
    state["handover_sale_at"] = now
    state["handover_by"] = ("(ลูกค้าขอเลิกคุย — รอผู้จัดการ)" if level >= 2
                            else "(บอทตอบไม่เข้าท่า — รอผู้จัดการ)")

    sig = "🛑 ลูกค้าขอเลิกคุย" if level >= 2 else "⚠️ บอทตอบไม่ตรง ลูกค้าทัก"
    sigs = state.setdefault("signals", [])
    if sig not in sigs:
        sigs.append(sig)
    try:
        engine._upsert_lead(state)
    except Exception as _e:
        print(f"[STOP UPSERT] {_e}")

    print(f"[STOP] {user_id[:8]}... ระดับ {level} "
          f"page={state.get('page_id') or '-'} "
          f"{('ปิดบอทถาวร' if level >= 2 else 'เงียบ+ส่งต่อคน') if first else 'สั่งไปแล้ว เงียบ'}"
          f" | {user_message[:60]!r}")

    if not first:
        return "", None

    msg = STOP_MSG if level >= 2 else STOP_SOFT_MSG
    if state.get("gender") == "female":
        try:
            from bot_logic import to_female
            msg = to_female(msg)
        except Exception as _e:
            print(f"[STOP FEMALE] {_e}")
    return msg, ("STOP" if level >= 2 else "STOPSOFT")


