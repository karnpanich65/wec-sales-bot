def _norm_zone_text(t: str) -> str:
    return (t or "").lower().replace("​", "")


def detect_zone(text: str):
    """ลูกค้าเอ่ยชื่อย่านไหม -> คืน (ชื่อย่านที่มีของ, ชื่อย่านที่ยังไม่มี)

    คืน ("", "") ถ้าไม่เจอ · ไม่โยน exception เด็ดขาด
    """
    try:
        t = _norm_zone_text(text)
        if not t:
            return "", ""
        for name, keys in ZONES_REAL:
            if any(k.lower() in t for k in keys):
                return name, ""
        for name, keys in ZONES_NONE:
            if any(k.lower() in t for k in keys):
                return "", name
        return "", ""
    except Exception:
        return "", ""


# งบเป็น "ล้าน" — จับ 2 ล้าน / 2.5 ล้าน / ไม่เกิน 3 ล้าน / งบ 3 ลิตร(ไม่เอา)
_BUDGET_RE = re.compile(r"(\d+(?:[.,]\d+)?)\s*(ล้าน|ลบ\.?|m\b)", re.I)
# กันคำที่มีตัวเลข+ล้าน แต่ไม่ใช่งบซื้อ
_BUDGET_SKIP = ("ล้านคน", "ล้านบาทต่อปี", "รายได้", "เงินเดือน", "กำไร")


def detect_budget(text: str) -> str:
    """จับงบซื้อหน่วยล้าน -> คืนข้อความสั้นๆ เช่น "3 ล้าน" (ไม่เจอ = "")"""
    try:
        t = (text or "")
        if not t:
            return ""
        if any(w in t for w in _BUDGET_SKIP):
            return ""
        m = _BUDGET_RE.search(t)
        if not m:
            return ""
        num = m.group(1).replace(",", ".")
        try:
            v = float(num)
        except Exception:
            return ""
        if not (0.3 <= v <= 100):      # นอกช่วงนี้ไม่ใช่งบคอนโด
            return ""
        return f"{num.rstrip('0').rstrip('.')} ล้าน"
    except Exception:
        return ""


